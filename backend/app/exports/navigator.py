"""ATT&CK Navigator layer export engine. Owner: Backend Core.

See team/03_BACKEND_CORE.md Step 6.
Exports ATT&CK Navigator Layer JSON format (version 4.5, ATT&CK v20).
"""
from __future__ import annotations

from app.models import ReportAnalysis


def build_navigator_layer(analysis: ReportAnalysis, include_predicted: bool = False) -> dict:
    """Build an ATT&CK Navigator layer JSON (v4.5) for ATT&CK v20.

    One entry per (technique, tactic) pair.
    Optionally includes predicted ghost techniques when include_predicted is True.
    """
    techniques: list[dict] = []

    # 1. Observed accepted techniques
    for t in analysis.techniques:
        if t.status != "accepted" or t.origin != "observed":
            continue

        score = round((t.confidence.mapping or 0.8) * 100)
        comment = t.evidence.quote[:250] if t.evidence else (t.rationale[:250] if t.rationale else "")

        for tactic in t.tactics:
            techniques.append({
                "techniqueID": t.technique_id,
                "tactic": tactic,
                "score": score,
                "comment": comment,
                "enabled": True,
                "showSubtechniques": True,
            })

    # 2. Predicted techniques (if requested)
    if include_predicted:
        for t in analysis.predictions:
            for tactic in t.tactics:
                techniques.append({
                    "techniqueID": t.technique_id,
                    "tactic": tactic,
                    "score": 0,
                    "color": "#a78bfa",
                    "comment": "Predicted (not observed) – hunt for these",
                    "enabled": True,
                    "showSubtechniques": True,
                })

    source_desc = f"Generated by TRINETRA from {analysis.source_url}" if analysis.source_url else "Generated by TRINETRA"

    return {
        "name": f"TRINETRA – {analysis.title or 'Threat Intelligence Report'}",
        "versions": {
            "attack": "20",
            "navigator": "5.1.0",
            "layer": "4.5",
        },
        "domain": "enterprise-attack",
        "description": source_desc,
        "sorting": 3,
        "layout": {
            "layout": "side",
            "showName": True,
            "showID": True,
        },
        "hideDisabled": False,
        "techniques": techniques,
        "gradient": {
            "colors": ["#1e293b", "#22d3ee"],
            "minValue": 0,
            "maxValue": 100,
        },
        "legendItems": [
            {"label": "Observed (score = confidence)", "color": "#22d3ee"},
            {"label": "Predicted – hunt for these", "color": "#a78bfa"},
        ],
        "showTacticRowBackground": True,
        "tacticRowBackground": "#0e1117",
        "selectTechniquesAcrossTactics": True,
        "selectSubtechniquesWithParent": False,
    }
